    '- ダウン/出撃 が 0 に近いと消耗ループが死んでいる。ガードの必要枚数か戦闘の長さを疑う',
    '- 交代なし が高すぎるなら物理スキルの配分が過剰',
    '- 前衛全滅 は染め編成のリスクが効いているかを見る。編成を選べるようになるまでは 0 で構わない',
    '- ボス到達 は雑魚戦の厳しさを見る。低いとボスの数字が測れない',
    '- ボスのターン は 50〜100 が設計目標。雑魚戦とは別の消耗戦にする。',
    '  ボスの通常攻撃が雑魚より軽いのは意図したもの。長期戦で成立する 1 ターンあたりの',
    '  被害は HP 予算を戦闘の長さで割った値になるため、脅威は大技に寄せてある',
    '- レベルは区画ごとの想定値 (浅層 1・中層 10・深層 20)、所持人数も想定値 (浅層 5・中層 12・',
